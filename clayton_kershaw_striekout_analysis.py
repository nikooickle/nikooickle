import pandas as pd
import numpy as np

pd.set_option('display.max_rows', 20)
pd.set_option('display.max_columns', 100)
pd.set_option('display.width', 1000)
pd.set_option('display.expand_frame_repr', False)
pd.set_option('display.max_colwidth', 100)

filename = 'clayton_kershaw_career_pitching_data.csv'
df = pd.read_csv(filename)

print("=== DATA OVERVIEW ===")
print(f"Rows: {df.shape[0]}, Columns: {df.shape[1]}")
print("\nFirst 10 rows:")
print(df.head(10))

print("\nLast 5 rows:")
print(df.tail(5))

print("\nColumn names:")
print(df.columns.tolist())

print("\nData types:")
print(df.dtypes)

print("\nMissing values:")
print(df.isnull().sum())

print("\nSummary statistics:")
print(df.describe(include='all').transpose())

print(f"\nDuplicate rows: {df.duplicated().sum()}")

print("\nRandom sample of 5 rows:")
print(df.sample(5))

strikeout_events = df[df['events'].isin(['strikeout', 'strikeout_double_play'])]

seasonal_stats = strikeout_events.groupby('game_year').agg(
    strikeouts=('events', 'count'),
    games_pitched=('game_date', 'nunique'),
    total_pitches=('pitch_type', 'count'),
    avg_release_speed=('release_speed', 'mean'),
    avg_spin_rate=('release_spin_rate', 'mean'),
    avg_release_extension=('release_extension', 'mean'),
    avg_spin_axis=('spin_axis', 'mean'),
    avg_release_pos_x=('release_pos_x', 'mean'),
    avg_release_pos_z=('release_pos_z', 'mean'),
    avg_pfx_x=('pfx_x', 'mean'),
    avg_pfx_z=('pfx_z', 'mean'),
    avg_plate_x=('plate_x', 'mean'),
    avg_plate_z=('plate_z', 'mean')
).reset_index()

seasonal_stats['strikeouts_per_game'] = seasonal_stats['strikeouts'] / seasonal_stats['games_pitched']

print("Seasonal Strikeout Statistics:")
print(seasonal_stats.sort_values('game_year', ascending=False))

# Count strikeouts per pitch type
strikeouts_by_pitch = strikeout_events['pitch_type'].value_counts()
print("\nStrikeouts by Pitch Type:")
print(strikeouts_by_pitch)

seasonal_stats_clean = seasonal_stats.copy()

seasonal_stats_clean['avg_spin_rate'] = seasonal_stats_clean['avg_spin_rate'].fillna(seasonal_stats_clean['avg_spin_rate'].mean())
seasonal_stats_clean['avg_release_extension'] = seasonal_stats_clean['avg_release_extension'].fillna(seasonal_stats_clean['avg_release_extension'].mean())
seasonal_stats_clean['avg_spin_axis'] = seasonal_stats_clean['avg_spin_axis'].fillna(seasonal_stats_clean['avg_spin_axis'].mean())

correlations = seasonal_stats_clean.drop(['game_year', 'strikeouts', 'games_pitched', 'total_pitches'], axis=1).corrwith(seasonal_stats_clean['strikeouts_per_game'])
correlations_sorted = correlations.sort_values(ascending=False)

print("Correlations with Strikeouts Per Game (sorted):")
print(correlations_sorted)

print("\nSummary statistics for potential predictors:")
print(seasonal_stats_clean.drop(['game_year', 'strikeouts', 'games_pitched', 'total_pitches'], axis=1).describe())

from sklearn.linear_model import LinearRegression
from sklearn.model_selection import train_test_split
from sklearn.metrics import r2_score

features = ['avg_release_pos_z', 'avg_release_speed', 'avg_spin_rate', 'avg_plate_z', 'avg_pfx_x', 'avg_spin_axis', 'avg_release_extension']
X = seasonal_stats_clean[features]
y = seasonal_stats_clean['strikeouts_per_game']

X_train = X[seasonal_stats_clean['game_year'] < 2024]
y_train = y[seasonal_stats_clean['game_year'] < 2024]
X_2024 = X[seasonal_stats_clean['game_year'] == 2024]

model = LinearRegression()
model.fit(X_train, y_train)

y_pred_train = model.predict(X_train)
print("Training R² Score:", r2_score(y_train, y_pred_train))

strikeouts_per_game_2024_pred = model.predict(X_2024)[0]
games_pitched_2024 = seasonal_stats_clean.loc[seasonal_stats_clean['game_year'] == 2024, 'games_pitched'].iloc[0]
predicted_strikeouts_2024 = strikeouts_per_game_2024_pred * games_pitched_2024

print(f"\nPredicted Strikeouts Per Game for 2024: {strikeouts_per_game_2024_pred:.2f}")
print(f"Predicted Total Strikeouts for 2024: {predicted_strikeouts_2024:.2f}")

seasonal_stats_2024= seasonal_stats_clean[seasonal_stats_clean['game_year'] == 2024]
print(f"\nActual Strikeouts Per Game for 2024: {seasonal_stats_2024['strikeouts_per_game'].iloc[0]}")
print(f"Predicted Strikeouts for 2024: {seasonal_stats_2024['strikeouts'].iloc[0]}")

model_accuracy = 1 - (seasonal_stats_2024['strikeouts'].iloc[0]-predicted_strikeouts_2024) / seasonal_stats_2024['strikeouts'].iloc[0]
print(f"\nModel Accuracy: {model_accuracy}")


feature_importance = pd.Series(model.coef_, index=features).sort_values(ascending=False)
print("\nFeature Importance (Coefficients):")
print(feature_importance)

max_strikeouts_year = seasonal_stats_clean.loc[seasonal_stats_clean['strikeouts_per_game'].idxmax(), 'game_year']
max_strikeouts_stats = seasonal_stats_clean[seasonal_stats_clean['game_year'] == max_strikeouts_year]
ideal_values = max_strikeouts_stats[features].iloc[0]

print(f"Year with Highest Strikeouts Per Game ({max_strikeouts_year}):")
print(f"Highest Strikeouts Per Game: {max_strikeouts_stats['strikeouts_per_game'].iloc[0]:.2f}")
print("\nIdeal Feature Values for Maximum Strikeouts:")
print(ideal_values)

strikeouts_2024_stats = seasonal_stats_clean[seasonal_stats_clean['game_year'] == 2024][features].iloc[0]
print("\n2024 Feature Values for Comparison:")
print(strikeouts_2024_stats)

differences = ideal_values - strikeouts_2024_stats
print("\nDifferences (Ideal - 2024):")
print(differences)

mean_values = seasonal_stats_clean[features].mean()


def predict_max_strikeouts_per_game(feature, direction):
    X_test = mean_values.copy()
    if direction == 'max':
        X_test[feature] = seasonal_stats_clean[feature].max()
    else:
        X_test[feature] = seasonal_stats_clean[feature].min()
    return model.predict([X_test])[0]

optimal_values = {}
for feature in features:
    coef = model.coef_[features.index(feature)]
    if coef > 0:
        optimal_values[feature] = seasonal_stats_clean[feature].max()
        max_strikeouts = predict_max_strikeouts_per_game(feature, 'max')
    else:
        optimal_values[feature] = seasonal_stats_clean[feature].min()
        max_strikeouts = predict_max_strikeouts_per_game(feature, 'min')
    print(f"\nOptimal {feature}: {optimal_values[feature]:.2f}")
    print(f"Predicted Strikeouts Per Game with optimal {feature}: {max_strikeouts:.2f}")

optimal_X = pd.Series(optimal_values)
max_strikeouts_per_game = model.predict([optimal_X])[0]
print(f"\nMaximum Predicted Strikeouts Per Game with all optimal values: {max_strikeouts_per_game:.2f}")